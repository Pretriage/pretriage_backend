-- Aplicar antes de iniciar la nueva versión sobre un esquema PostgreSQL existente.
-- Las marcas históricas quedan anuladas porque el criterio previo era diferente.
BEGIN;

CREATE TABLE IF NOT EXISTS discrepancia_sintomas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atencion_medica bigint NOT NULL UNIQUE REFERENCES atencion_medica (id),
    motivo varchar(500),
    registrada_en timestamp(6) with time zone NOT NULL
);

ALTER TABLE discrepancia_sintomas
    ALTER COLUMN motivo DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS dni varchar(8),
    ADD COLUMN IF NOT EXISTS estado varchar(16) NOT NULL DEFAULT 'ANULADA'
        CHECK (estado IN ('VIGENTE', 'ANULADA')),
    ADD COLUMN IF NOT EXISTS anulada_en timestamp(6) with time zone,
    ADD COLUMN IF NOT EXISTS anulada_por_id varchar(255) REFERENCES usuario_auth (id);

WITH documentos AS (
    SELECT d.id,
           CASE WHEN u.tipo_documento IS NOT NULL OR u.numero_documento IS NOT NULL
                THEN u.tipo_documento ELSE p.tipo_documento END AS tipo,
           replace(btrim(CASE WHEN u.tipo_documento IS NOT NULL OR u.numero_documento IS NOT NULL
                              THEN u.numero_documento ELSE p.numero_documento END), '.', '') AS digitos
    FROM discrepancia_sintomas d
    JOIN atencion_medica a ON a.id = d.id_atencion_medica
    JOIN consulta_medica c ON c.id = a.id_consulta_medica
    JOIN paciente p ON p.id = c.id_paciente
    LEFT JOIN usuario_auth u ON u.id = p.auth_id
    WHERE d.estado = 'ANULADA' AND d.anulada_en IS NULL AND d.dni IS NULL
)
UPDATE discrepancia_sintomas d
SET dni = ltrim(documentos.digitos, '0')
FROM documentos
WHERE d.id = documentos.id AND documentos.tipo = 'DNI'
  AND documentos.digitos ~ '^[0-9]{7,8}$' AND ltrim(documentos.digitos, '0') <> '';

CREATE INDEX IF NOT EXISTS idx_discrepancia_dni_estado_fecha
    ON discrepancia_sintomas (dni, estado, registrada_en);

CREATE TABLE IF NOT EXISTS sancion_digital_paciente (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discrepancia_id bigint NOT NULL REFERENCES discrepancia_sintomas (id),
    dni varchar(8) NOT NULL,
    calculada_en timestamp(6) with time zone NOT NULL,
    cantidad_vigentes bigint NOT NULL,
    fecha_inicio timestamp(6) with time zone,
    fecha_fin timestamp(6) with time zone,
    permanente boolean NOT NULL,
    aviso_id varchar(64),
    tipo_aviso varchar(16) CHECK (tipo_aviso IN ('APLICADA', 'LEVANTADA'))
);

CREATE INDEX IF NOT EXISTS idx_sancion_dni_id ON sancion_digital_paciente (dni, id);

COMMIT;
